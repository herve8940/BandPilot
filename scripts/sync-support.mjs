// Static links only: no payment widget, analytics, or request to Ko-fi on page load.
import {readFileSync, writeFileSync, existsSync, unlinkSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => readFileSync(resolve(root, path), 'utf8');
const config = JSON.parse(read('config/support.json'));
const translations = JSON.parse(read('config/support-copy.json'));
const args = process.argv.slice(2);
const check = args.length === 1 && args[0] === '--check';
if (args.length && !check && !(args.length === 1 && args[0] === '--disable') && !(args.length === 2 && args[0] === '--username')) {
  throw Error('Usage: node scripts/sync-support.mjs [--check | --username VERIFIED_USERNAME | --disable]');
}
if (args[0] === '--username') config.koFiUsername = args[1];
if (args[0] === '--disable') config.koFiUsername = null;
if (config.koFiUsername !== null && (typeof config.koFiUsername !== 'string' || (!/^[a-zA-Z0-9_]{2,50}$/.test(config.koFiUsername) || /^(IDENTIFIANT_VERIFIE|USERNAME|YOUR_USERNAME)$/i.test(config.koFiUsername)))) {
  throw Error('Use the verified Ko-fi username only, not a URL or a placeholder.');
}
const url = config.koFiUsername ? `https://ko-fi.com/${config.koFiUsername}` : null;
const outputs = new Map();
const html = value => value.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
function replaceBlock(path, key, body) {
  const start = `<!-- ${key}:start -->`, end = `<!-- ${key}:end -->`;
  const source = read(path), a = source.indexOf(start), b = source.indexOf(end);
  if (a < 0 || b < a || source.indexOf(start, a + start.length) >= 0 || source.indexOf(end, b + end.length) >= 0) {
    throw Error(`Missing or duplicate ${key} markers in ${path}`);
  }
  outputs.set(path, source.slice(0, a) + start + '\n' + body + '\n' + end + source.slice(b + end.length));
}
for (const [lang, copy] of Object.entries(translations)) {
  const page = `SUPPORT_${lang.toUpperCase()}`;
  const action = url ? `[${copy.kofi}](${url})` : copy.pending;
  const links = Object.entries(translations).map(([code, text]) => `[${text.language}](SUPPORT_${code.toUpperCase()}.md)`).join(' · ');
  outputs.set(`docs/${page}.md`, `---\nlang: ${lang}\ntitle: ${JSON.stringify(copy.title)}\n---\n\n<!-- Generated by scripts/sync-support.mjs; edit config/support-copy.json. -->\n# ${copy.title}\n\n${links}\n\n${copy.intro}\n\n## ${copy.whyTitle}\n\n${copy.reasons.map(reason => '- ' + reason).join('\n')}\n\n${copy.terms}\n\n## ${copy.moneyTitle}\n\n${action}\n\n${copy.privacy}\n\n## ${copy.otherTitle}\n\n${copy.other}\n\n[${copy.contribute}](https://github.com/herve8940/BandPilot/blob/main/CONTRIBUTING.md) · [${copy.report}](https://github.com/herve8940/BandPilot/issues/new/choose) · [${copy.privacyLabel} (FR / EN)](PRIVACY.md)\n`);
  replaceBlock(lang === 'fr' ? 'README.md' : `README.${lang}.md`, 'support', `## ${copy.title}\n\n${copy.intro}\n\n${copy.summary}\n\n${url ? `[${copy.kofi}](${url}) · ` : ''}[${copy.more}](docs/${page}.md) · [${copy.contribute}](CONTRIBUTING.md)`);
  const button = url ? `<a class="btn primary" href="${url}" rel="noopener noreferrer">${html(copy.kofi)}</a>` : '';
  replaceBlock(lang === 'fr' ? 'docs/index.html' : `docs/${lang}.html`, 'support', `<section id="support"><div class="wrap"><span class="badge">${html(copy.badge)}</span><h2>${html(copy.title)}</h2><p class="lead">${html(copy.intro)}</p><div class="grid">${copy.reasons.map((reason, i) => `<article class="card"><h3>${html(copy.reasonTitles[i])}</h3><p>${html(reason)}</p></article>`).join('')}</div><p>${html(copy.terms)}</p><div class="actions">${button}<a class="btn" href="${page}.html">${html(copy.more)}</a><a class="btn" href="https://github.com/herve8940/BandPilot/blob/main/CONTRIBUTING.md">${html(copy.contribute)}</a></div>${url ? '' : `<p class="muted">${html(copy.pending)}</p>`}</div></section>`);
}
outputs.set('config/support.json', JSON.stringify(config, null, 2) + '\n');
if (url) outputs.set('.github/FUNDING.yml', `# Generated by scripts/sync-support.mjs from the verified project account.\nko_fi: ${config.koFiUsername}\n`);
const funding = resolve(root, '.github/FUNDING.yml');
if (!url && existsSync(funding) && !read('.github/FUNDING.yml').startsWith('# Generated by scripts/sync-support.mjs')) {
  throw Error('Review the existing FUNDING.yml manually.');
}
let dirty = false;
for (const [path, content] of outputs) {
  if (existsSync(resolve(root, path)) && read(path) === content) continue;
  dirty = true;
  if (check) console.error(`Out of date: ${path}`);
  else writeFileSync(resolve(root, path), content);
}
if (!url && existsSync(funding)) {
  dirty = true;
  if (!check) unlinkSync(funding);
}
if (check && dirty) process.exitCode = 1;
else console.log(`Support pages ${check ? 'verified' : 'synchronized'}; Ko-fi ${url ? 'enabled' : 'not configured'}.`);
