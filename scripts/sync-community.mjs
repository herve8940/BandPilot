// Keep public invitations and translated community presentations in sync.
// Plain links only: no Discord widget, SDK, analytics or network request.
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => readFileSync(resolve(root, path), 'utf8');
const config = JSON.parse(read('config/community.json'));
const translations = JSON.parse(read('config/community-copy.json'));
const check = process.argv.length === 3 && process.argv[2] === '--check';
if (process.argv.length > 2 && !check) throw Error('Usage: node scripts/sync-community.mjs [--check]');
if (!/^https:\/\/discord\.gg\/[A-Za-z0-9]+$/.test(config.inviteUrl)) throw Error('Use a verified Discord invitation URL.');
if (!/^\d{17,20}$/.test(config.serverId)) throw Error('Invalid Discord server ID.');
for (const destination of ['help', 'bugs', 'guide', 'ideas']) {
  const channel = config.channels?.[destination];
  if (!/^\d{17,20}$/.test(channel?.id) || !/^[a-z0-9-]+$/.test(channel?.name)) throw Error(`Invalid Discord channel: ${destination}`);
}
const channels = ['accueil-welcome', 'annonces-news', 'demarrer-start-here', 'discussion-general', 'entraide-help', 'idees-feedback', 'bugs-tests'];
const html = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const channelUrl = destination => `https://discord.com/channels/${config.serverId}/${config.channels[destination].id}`;
const channelLink = name => {
  const destination = Object.keys(config.channels).find(key => config.channels[key].name === name);
  return destination ? `[#${name}](${channelUrl(destination)})` : `#${name}`;
};
const outputs = new Map();
function block(source, key, body, path) {
  const start = `<!-- ${key}:start -->`, end = `<!-- ${key}:end -->`;
  const a = source.indexOf(start), b = source.indexOf(end);
  if (a < 0 || b < a || source.indexOf(start, a + start.length) >= 0 || source.indexOf(end, b + end.length) >= 0) throw Error(`Missing or duplicate ${key} markers in ${path}`);
  return source.slice(0, a) + start + '\n' + body + '\n' + end + source.slice(b + end.length);
}
for (const [lang, copy] of Object.entries(translations)) {
  if (copy.channels.length !== channels.length) throw Error(`Channel descriptions missing in ${lang}`);
  const page = `COMMUNITY_${lang.toUpperCase()}`;
  const links = Object.entries(translations).map(([code, text]) => `[${text.language}](COMMUNITY_${code.toUpperCase()}.md)`).join(' · ');
  const join = `[${copy.join}](${config.inviteUrl})`;
  const inApp = `### ${copy.inAppTitle}\n\n${copy.inAppText}\n\n[${copy.help}](${channelUrl('help')}) · [${copy.bugs}](${channelUrl('bugs')})`;
  const inAppHtml = `<h3>${html(copy.inAppTitle)}</h3><p>${html(copy.inAppText)}</p><div class="actions"><a class="btn primary" href="${channelUrl('help')}" rel="noopener noreferrer">${html(copy.help)}</a><a class="btn" href="${channelUrl('bugs')}" rel="noopener noreferrer">${html(copy.bugs)}</a></div>`;
  outputs.set(`docs/${page}.md`, `---\nlang: ${lang}\ntitle: ${JSON.stringify(copy.title)}\ndescription: ${JSON.stringify(copy.summary)}\n---\n\n<!-- Generated by scripts/sync-community.mjs; edit config/community.json and config/community-copy.json. -->\n# ${copy.title}\n\n${links}\n\n${copy.intro}\n\n**${join}**\n\n${copy.summary}\n\n${inApp}\n\n## ${copy.channelsTitle}\n\n| ${copy.channelLabel} | ${copy.purposeLabel} |\n|---|---|\n${channels.map((channel, i) => `| ${channelLink(channel)} | ${copy.channels[i]} |`).join('\n')}\n\n${copy.voice}\n\n## ${copy.startTitle}\n\n${copy.start}\n\n## ${copy.rulesTitle}\n\n${copy.rules}\n\n${copy.tracking}\n\n[${copy.issues}](https://github.com/herve8940/BandPilot/issues/new/choose) · [${copy.security}](https://github.com/herve8940/BandPilot/blob/main/SECURITY.md)\n\n${copy.privacy}\n\n${copy.independent}\n`);
  const readmePath = lang === 'fr' ? 'README.md' : `README.${lang}.md`;
  let readme = read(readmePath);
  readme = block(readme, 'community-badge', `[![Discord](https://img.shields.io/badge/Discord-BandPilot-5865F2?logo=discord&logoColor=white)](${config.inviteUrl})`, readmePath);
  readme = block(readme, 'community', `\n## ${copy.title}\n\n${copy.intro}\n\n${copy.summary}\n\n**${join}** · [${copy.more}](docs/${page}.md)\n\n${inApp}`, readmePath);
  outputs.set(readmePath, readme);
  const sitePath = lang === 'fr' ? 'docs/index.html' : `docs/${lang}.html`;
  outputs.set(sitePath, block(read(sitePath), 'community', `<section id="community"><div class="wrap"><span class="badge">BandPilot · Discord</span><h2>${html(copy.title)}</h2><p class="lead">${html(copy.intro)}</p><div class="grid">${copy.benefits.map(([title, text]) => `<article class="card"><h3>${html(title)}</h3><p>${html(text)}</p></article>`).join('')}</div><p>${html(copy.summary)}</p>${inAppHtml}<div class="actions"><a class="btn primary" href="${config.inviteUrl}" rel="noopener noreferrer">${html(copy.join)}</a><a class="btn" href="${page}.html">${html(copy.more)}</a></div></div></section>`, sitePath));
}
let dirty = false;
for (const [path, content] of outputs) {
  if (existsSync(resolve(root, path)) && read(path) === content) continue;
  dirty = true;
  if (check) console.error(`Out of date: ${path}`);
  else writeFileSync(resolve(root, path), content);
}
if (check && dirty) process.exitCode = 1;
else console.log(`Community pages ${check ? 'verified' : 'synchronized'}.`);
